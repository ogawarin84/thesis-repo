# Group by condition
conds = {'R1':[],'R2':[],'R3':[],'R4':[],'R5':[],'R6':[]}
for row in data:
    r = row[1]
    conds[r].append(row)

def stats_arr(vals, label):
    v = np.array(vals)
    n = len(v)
    m = np.mean(v)
    s = np.std(v, ddof=1)
    print(f"  {label}: n={n}, mean={m:.4f}, sd={s:.4f}")
    return m, s

print("="*60)
